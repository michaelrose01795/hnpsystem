const fs = require("fs");
const path = require("path");

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, "src");
const OUT_FILE = path.join(SRC_DIR, "lib", "dev-layout", "sectionSourceMap.generated.js");
// The hash is emitted to its OWN module as well as into the map file. Anything on
// the client boot path (SupportReportContext stamps every report with it) must be
// able to read the hash without pulling the ~155KB map array in with it — a
// re-export from the map file does not tree-shake, so the map ended up in the
// first-load bundle of 54 page routes.
const HASH_OUT_FILE = path.join(SRC_DIR, "lib", "dev-layout", "sectionSourceMapHash.generated.js");

const EXTENSIONS = new Set([".js", ".jsx", ".ts", ".tsx"]);
const IGNORE_DIRS = new Set(["node_modules", ".next", ".git"]);

const toPosix = (value) => value.split(path.sep).join("/");

const escapeForJs = (value) =>
  String(value || "")
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");

const walk = (dir, files = []) => {
  fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
    if (IGNORE_DIRS.has(entry.name)) return;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, files);
      return;
    }
    if (EXTENSIONS.has(path.extname(entry.name))) {
      files.push(fullPath);
    }
  });
  return files;
};

const getLineNumber = (text, index) => text.slice(0, index).split(/\r?\n/).length;

const normalizeTemplatePattern = (value) =>
  String(value || "")
    .replace(/\$\{[^}]+\}/g, "*")
    .replace(/`/g, "")
    .trim();

const collectMatches = (filePath) => {
  const text = fs.readFileSync(filePath, "utf8");
  const relPath = toPosix(path.relative(ROOT, filePath));
  const matches = [];
  const seen = new Set();
  const patterns = [
    {
      prop: "sectionKey",
      regex: /sectionKey\s*=\s*(?:"([^"]+)"|'([^']+)'|`([^`]+)`|\{`([^`]+)`\}|\{"([^"]+)"\}|\{'([^']+)'\})/g,
    },
    {
      prop: "headerSectionKey",
      regex: /headerSectionKey\s*=\s*(?:"([^"]+)"|'([^']+)'|`([^`]+)`|\{`([^`]+)`\}|\{"([^"]+)"\}|\{'([^']+)'\})/g,
    },
    {
      prop: "contentSectionKey",
      regex: /contentSectionKey\s*=\s*(?:"([^"]+)"|'([^']+)'|`([^`]+)`|\{`([^`]+)`\}|\{"([^"]+)"\}|\{'([^']+)'\})/g,
    },
    {
      prop: "data-dev-section-key",
      regex: /data-dev-section-key\s*=\s*(?:"([^"]+)"|'([^']+)'|`([^`]+)`|\{`([^`]+)`\}|\{"([^"]+)"\}|\{'([^']+)'\})/g,
    },
  ];

  patterns.forEach(({ prop, regex }) => {
    let match;
    while ((match = regex.exec(text))) {
      const rawValue = match.slice(1).find((value) => value != null) || "";
      const pattern = normalizeTemplatePattern(rawValue);
      if (!pattern) continue;
      const line = getLineNumber(text, match.index);
      const dedupeKey = `${pattern}:${relPath}:${line}:${prop}`;
      if (seen.has(dedupeKey)) continue;
      seen.add(dedupeKey);
      matches.push({
        key: pattern,
        file: relPath,
        line,
        prop,
        dynamic: pattern.includes("*"),
      });
    }
  });

  return matches;
};

const entries = walk(SRC_DIR)
  .flatMap(collectMatches)
  .sort((left, right) => {
    if (left.key !== right.key) return left.key.localeCompare(right.key);
    if (left.file !== right.file) return left.file.localeCompare(right.file);
    return left.line - right.line;
  });

// Stable content hash (djb2) of the ordered entries. Help & Diagnostics (Phase 5)
// uses this to verify a captured report's file:line was resolved against the SAME
// section map that shipped in the deployed build, and to detect code drift when
// the map has moved since a report was captured. Must match the djb2 in
// src/lib/support/incidentClustering.js (stableHash) so both layers agree.
const djb2 = (str) => {
  let hash = 5381;
  for (let i = 0; i < str.length; i += 1) {
    hash = ((hash << 5) + hash + str.charCodeAt(i)) & 0xffffffff;
  }
  return (hash >>> 0).toString(36);
};
const MAP_HASH = djb2(
  entries.map((e) => `${e.key}|${e.file}|${e.line}|${e.prop}`).join("\n")
);

const output = `// Generated by tools/scripts/generate-dev-layout-section-source-map.js.
// Do not edit by hand; rerun the generator after adding or moving dev layout section keys.
export const DEV_LAYOUT_SECTION_SOURCE_MAP = [
${entries
  .map(
    (entry) =>
      `  { key: \`${escapeForJs(entry.key)}\`, file: \`${escapeForJs(entry.file)}\`, line: ${entry.line}, prop: \`${entry.prop}\`, dynamic: ${entry.dynamic} },`
  )
  .join("\n")}
];

// Stable hash of the map above (Help & Diagnostics Phase 5 — code-state pinning).
export const DEV_LAYOUT_SECTION_SOURCE_MAP_HASH = ${JSON.stringify(MAP_HASH)};
`;

const hashOutput = `// Generated by tools/scripts/generate-dev-layout-section-source-map.js.
// Do not edit by hand; rerun the generator after adding or moving dev layout section keys.
//
// Hash-only companion to sectionSourceMap.generated.js. Kept separate so the
// client boot path can stamp a report with the deployed map's hash without
// importing the map itself.
export const DEV_LAYOUT_SECTION_SOURCE_MAP_HASH = ${JSON.stringify(MAP_HASH)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output, "utf8");
fs.writeFileSync(HASH_OUT_FILE, hashOutput, "utf8");

// ---------------------------------------------------------------------------
// Website class map (src/lib/dev-layout/websiteClassSourceMap.js)
// ---------------------------------------------------------------------------
// /website registers no section keys; the overlay locates a customer card by its
// `ws-*` / `website-*` classes. Every class literal in the customer source files
// is recorded against the file + line that renders it. Written to its own file so
// the section map above (and its diagnostics hash) is unaffected.
const WEBSITE_CLASS_OUT_FILE = path.join(SRC_DIR, "lib", "dev-layout", "websiteClassSourceMap.generated.js");
const WEBSITE_SOURCE_ROOTS = ["src/pages/website", "src/features/website", "src/pages/website.js", "src/components/layout/CustomerWebsiteLayout.js"];
const WEBSITE_CLASS_TOKEN = /^(?:ws|website)-[a-z0-9_-]+$/i;

const isWebsiteSourceFile = (relPath) =>
  WEBSITE_SOURCE_ROOTS.some((root) => relPath === root || relPath.startsWith(`${root}/`));

const collectWebsiteClassMatches = (filePath) => {
  const relPath = toPosix(path.relative(ROOT, filePath));
  if (!isWebsiteSourceFile(relPath)) return [];
  const text = fs.readFileSync(filePath, "utf8");
  const matches = [];
  const seen = new Set();
  // className="a b" | className={"a"} | className={cond ? "a" : "b"} | className={`a ${b}`}
  const attributeRegex = /className\s*=\s*(\{[^}]*\}|"[^"]*"|'[^']*')/g;
  let match;
  while ((match = attributeRegex.exec(text))) {
    const line = getLineNumber(text, match.index);
    const tokens = match[1].replace(/\$\{[^}]*\}/g, " ").match(/[A-Za-z0-9_-]+/g) || [];
    tokens.forEach((token) => {
      if (!WEBSITE_CLASS_TOKEN.test(token)) return;
      // One entry per class per file: the first line that renders it.
      if (seen.has(token)) return;
      seen.add(token);
      matches.push({ className: token, file: relPath, line });
    });
  }
  return matches;
};

const websiteClassEntries = walk(SRC_DIR)
  .flatMap(collectWebsiteClassMatches)
  .sort((left, right) => {
    if (left.className !== right.className) return left.className.localeCompare(right.className);
    if (left.file !== right.file) return left.file.localeCompare(right.file);
    return left.line - right.line;
  });

const websiteClassOutput = `// Generated by tools/scripts/generate-dev-layout-section-source-map.js.
// Do not edit by hand; rerun the generator (npm run dev-layout:source-map) after adding or moving /website classes.
export const WEBSITE_CLASS_SOURCE_MAP = [
${websiteClassEntries
  .map(
    (entry) =>
      `  { className: \`${escapeForJs(entry.className)}\`, file: \`${escapeForJs(entry.file)}\`, line: ${entry.line} },`
  )
  .join("\n")}
];
`;

fs.writeFileSync(WEBSITE_CLASS_OUT_FILE, websiteClassOutput, "utf8");

console.log(`Wrote ${entries.length} dev layout section source entries (hash ${MAP_HASH}) to ${toPosix(path.relative(ROOT, OUT_FILE))}`);
console.log(`Wrote ${websiteClassEntries.length} website class source entries to ${toPosix(path.relative(ROOT, WEBSITE_CLASS_OUT_FILE))}`);
// Emit the hash on its own line so CI can capture it into NEXT_PUBLIC_SECTION_MAP_HASH.
console.log(`SECTION_MAP_HASH=${MAP_HASH}`);
